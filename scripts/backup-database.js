import { createClient } from '@supabase/supabase-js'
import fs from 'fs'
import path from 'path'
import { exec } from 'child_process'
import { promisify } from 'util'
import { fileURLToPath } from 'url'
import { dirname } from 'path'

const __filename = fileURLToPath(import.meta.url)
const __dirname = dirname(__filename)

const execPromise = promisify(exec)

// Load environment variables
const SUPABASE_URL = process.env.NEXT_PUBLIC_SUPABASE_URL
const SUPABASE_SERVICE_KEY = process.env.SUPABASE_SERVICE_KEY
const SUPABASE_DB_PASSWORD = process.env.SUPABASE_DB_PASSWORD

if (!SUPABASE_URL || !SUPABASE_SERVICE_KEY) {
  console.error('[Backup] ❌ Missing required environment variables!')
  console.error('[Backup] Required: NEXT_PUBLIC_SUPABASE_URL, SUPABASE_SERVICE_KEY')
  process.exit(1)
}

const PROJECT_REF = SUPABASE_URL.match(/https:\/\/([^.]+)/)[1]

// Backup configuration
const BACKUP_DIR = path.join(dirname(__dirname), 'backups')
const MAX_BACKUPS = 7 // Keep last 7 backups

async function createBackup() {
  console.log('[Backup] Starting database backup...')
  console.log(`[Backup] Project: ${PROJECT_REF}`)
  
  // Create backup directory if it doesn't exist
  if (!fs.existsSync(BACKUP_DIR)) {
    fs.mkdirSync(BACKUP_DIR, { recursive: true })
    console.log(`[Backup] Created backup directory: ${BACKUP_DIR}`)
  }

  // Generate filename with timestamp
  const timestamp = new Date().toISOString().replace(/[:.]/g, '-').split('T')[0]
  const filename = `backup-${timestamp}.sql`
  const filepath = path.join(BACKUP_DIR, filename)

  try {
    if (SUPABASE_DB_PASSWORD) {
      // Method 1: Use pg_dump (requires PostgreSQL client installed)
      console.log('[Backup] Attempting pg_dump method...')
      const dbUrl = `postgresql://postgres:${SUPABASE_DB_PASSWORD}@db.${PROJECT_REF}.supabase.co:5432/postgres`
      
      await execPromise(`pg_dump "${dbUrl}" > "${filepath}"`)
      
      console.log('[Backup] ✅ Database backed up successfully using pg_dump!')
      console.log(`[Backup] File: ${filepath}`)
      console.log(`[Backup] Size: ${(fs.statSync(filepath).size / 1024).toFixed(2)} KB`)
    } else {
      throw new Error('SUPABASE_DB_PASSWORD not set, using fallback method')
    }
  } catch (error) {
    console.log('[Backup] pg_dump not available or failed, using fallback method...')
    console.log(`[Backup] Error: ${error.message}`)
    
    // Fallback: Manual data export
    await fallbackBackup(filepath)
  }

  // Clean up old backups
  await cleanupOldBackups()

  return filepath
}

async function fallbackBackup(filepath) {
  console.log('[Backup] Starting fallback backup (manual export)...')
  
  // If pg_dump is not available, export data manually
  const supabase = createClient(SUPABASE_URL, SUPABASE_SERVICE_KEY)

  const tables = ['users', 'personas', 'conversations', 'messages']
  let sqlDump = `-- Database Backup: ${new Date().toISOString()}\n`
  sqlDump += `-- Generated by fallback method (Supabase API export)\n\n`

  for (const table of tables) {
    console.log(`[Backup] Exporting table: ${table}`)
    
    const { data, error } = await supabase
      .from(table)
      .select('*')
    
    if (error) {
      console.error(`[Backup] Error exporting ${table}:`, error.message)
      continue
    }

    // Convert to SQL INSERT statements
    if (data && data.length > 0) {
      sqlDump += `-- Table: ${table} (${data.length} rows)\n`
      sqlDump += `-- DELETE FROM ${table};\n`
      
      data.forEach(row => {
        const columns = Object.keys(row).join(', ')
        const values = Object.values(row).map(v => {
          if (v === null) return 'NULL'
          if (typeof v === 'string') return `'${v.replace(/'/g, "''")}'`
          if (typeof v === 'boolean') return v
          if (typeof v === 'object') return `'${JSON.stringify(v).replace(/'/g, "''")}'`
          return v
        }).join(', ')
        
        sqlDump += `INSERT INTO ${table} (${columns}) VALUES (${values});\n`
      })
      
      sqlDump += '\n'
      console.log(`[Backup] ✅ Exported ${data.length} rows from ${table}`)
    } else {
      sqlDump += `-- Table: ${table} (empty)\n\n`
      console.log(`[Backup] ℹ️ Table ${table} is empty`)
    }
  }

  fs.writeFileSync(filepath, sqlDump, 'utf8')
  const fileSize = (fs.statSync(filepath).size / 1024).toFixed(2)
  
  console.log('[Backup] ✅ Fallback backup completed!')
  console.log(`[Backup] File: ${filepath}`)
  console.log(`[Backup] Size: ${fileSize} KB`)
}

async function cleanupOldBackups() {
  const files = fs.readdirSync(BACKUP_DIR)
    .filter(f => f.startsWith('backup-') && f.endsWith('.sql'))
    .map(f => ({
      name: f,
      path: path.join(BACKUP_DIR, f),
      time: fs.statSync(path.join(BACKUP_DIR, f)).mtime.getTime()
    }))
    .sort((a, b) => b.time - a.time)

  if (files.length > MAX_BACKUPS) {
    const toDelete = files.slice(MAX_BACKUPS)
    console.log(`[Backup] Cleaning up ${toDelete.length} old backup(s)...`)
    
    toDelete.forEach(file => {
      fs.unlinkSync(file.path)
      console.log(`[Backup] Deleted: ${file.name}`)
    })
  } else {
    console.log(`[Backup] Current backups: ${files.length}/${MAX_BACKUPS}`)
  }
}

// Run backup
createBackup()
  .then(() => {
    console.log('[Backup] ✅ Backup process completed successfully!')
    process.exit(0)
  })
  .catch(error => {
    console.error('[Backup] ❌ Fatal error:', error)
    process.exit(1)
  })
